import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {watch,problemCount} from '../../../tools/console-probe.mjs';
const output='tmp/flythrough-review';
mkdirSync(output,{recursive:true});
const base=process.env.VILLA_URL || 'http://127.0.0.1:4321';
const browser=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const report={};
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 const watcher=watch(page);
 await page.goto(base+'/?view=scene');
 await page.waitForFunction(()=>window.__villaReady===0);
 await page.waitForTimeout(400);
 assert.equal((await page.evaluate(()=>window.__villaTravel())).u,0);
 await page.evaluate(()=>{
   window.flightSamples=[];window.samplingFlight=true;
   const tick=t=>{if(!window.samplingFlight)return;window.flightSamples.push({t,...window.__villaTravel()});requestAnimationFrame(tick);};
   requestAnimationFrame(tick);
 });
 await page.mouse.move(900,350);
 await page.mouse.wheel(0,100); // One event for the entire outward flight.
 await page.waitForFunction(()=>window.__villaTravel().speed===1.2,null,{timeout:15000});
 await page.waitForTimeout(4000);
 assert.equal((await page.evaluate(()=>window.__villaTravel())).speed,1.2);
 await page.screenshot({path:output+'/desktop-flight.png'});
 await page.waitForFunction(()=>window.__villaTravel().u===1,null,{timeout:150000});
 const forward=await page.evaluate(()=>window.flightSamples);
 const total=forward.at(-1).metres;
 const verify=(samples,direction)=>{
   const order=[...new Set(samples.map(s=>s.viewpoint))];
   assert.deepEqual(order,Array.from({length:14},(_,i)=>direction>0?i:13-i));
   assert.ok(samples.every((s,i)=>!i||direction*(s.u-samples[i-1].u)>=-1e-12));
   const cruise=samples.filter(s=>s.metres>2 && s.metres<total-2);
   assert.ok(cruise.length>100);
   assert.ok(cruise.every(s=>s.speed===direction*1.2 && s.acceleration===0 && s.jerk===0));
   return {frames:samples.length,seconds:(samples.at(-1).t-samples[0].t)/1000,order,cruiseFrames:cruise.length,cruiseSpeed:direction*1.2};
 };
 report.forward=verify(forward,1);
 await page.screenshot({path:output+'/terrace.png'});
 console.log('PASS one wheel event: every room, uninterrupted 1.2 m/s cruise, smooth arrival');
 await page.evaluate(()=>{window.flightSamples=[];});
 await page.getByRole('button',{name:'Fly back the flight'}).click();
 await page.waitForFunction(()=>window.__villaTravel().speed<0);
 await page.waitForFunction(()=>window.__villaTravel().u===0,null,{timeout:150000});
 const reverse=await page.evaluate(()=>{window.samplingFlight=false;return window.flightSamples;});
 report.reverse=verify(reverse,-1);
 assert.equal(problemCount(watcher.found),0,JSON.stringify(watcher.found));
 report.desktopProblems=watcher.found;
 console.log('PASS return flight: every room in reverse, uninterrupted cruise');
 watcher.stop(); await page.close();

 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
 const mobile=await context.newPage(); const mobileWatcher=watch(mobile);
 await mobile.goto(base+'/?view=scene&vp=5');
 await mobile.waitForFunction(()=>window.__villaReady===5);
 const client=await context.newCDPSession(mobile);
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:290,y:350}]});
 await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:290,y:270}]});
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await mobile.waitForFunction(()=>window.__villaTravel().speed===1.2,null,{timeout:15000});
 await mobile.waitForTimeout(2000);
 assert.equal((await mobile.evaluate(()=>window.__villaTravel())).speed,1.2);
 await mobile.getByRole('button',{name:'Pause the flight'}).click();
 await mobile.waitForFunction(()=>window.__villaTravel().mode==='paused',null,{timeout:10000});
 const paused=await mobile.evaluate(()=>window.__villaTravel());
 await mobile.waitForTimeout(600);
 assert.deepEqual(await mobile.evaluate(()=>window.__villaTravel()),paused);
 await mobile.screenshot({path:output+'/mobile-paused.png'});
 assert.ok(await mobile.evaluate(()=>document.body.scrollWidth<=innerWidth));
 await mobile.getByRole('button',{name:'Resume the flight'}).click();
 await mobile.waitForFunction(()=>window.__villaTravel().speed===1.2,null,{timeout:10000});
 await mobile.evaluate(()=>document.activeElement?.blur());
 await mobile.keyboard.press('Space');
 await mobile.waitForFunction(()=>window.__villaTravel().mode==='paused',null,{timeout:10000});
 await mobile.goto(base+'/?view=scene&vp=9');
 await mobile.waitForFunction(()=>window.__villaReady===9);
 await mobile.locator('#index-toggle').click();
 assert.equal(await mobile.locator('dialog[open]').count(),1);
 await mobile.locator('#project-dialog [data-project="quilt-trader"]').click();
 await mobile.waitForFunction(()=>window.__villaTravel().mode==='visit');
 await mobile.waitForFunction(()=>window.__villaTravel().mode==='paused',null,{timeout:30000});
 assert.equal(await mobile.locator('#panels .panel:visible').getAttribute('data-stop'),'quilt-trader');
 await mobile.locator('#panels .panel:visible summary').click();
 const reading=await mobile.evaluate(()=>window.__villaTravel().u);
 await mobile.locator('#panels .panel:visible .details-body').hover();
 await mobile.mouse.wheel(0,200);
 await mobile.waitForTimeout(500);
 assert.equal(await mobile.evaluate(()=>window.__villaTravel().u),reading);
 await mobile.screenshot({path:output+'/mobile-project.png'});
 assert.equal(problemCount(mobileWatcher.found),0,JSON.stringify(mobileWatcher.found));
 report.mobile={touchCruise:true,pauseStable:true,resume:true,spacePause:true,projectNavigation:true,readingStable:true,noOverflow:true,problems:mobileWatcher.found};
 mobileWatcher.stop(); await context.close();
 console.log('PASS mobile swipe starts ongoing cruise; pause/resume/Space; no overflow or browser errors');
 writeFileSync(output+'/browser-results.json',JSON.stringify(report,null,2)+'\n');
}finally{await browser.close();}
